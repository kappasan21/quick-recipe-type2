/**
 * Translate Japanese ingredients to English
 */
export function translateJapaneseToEnglish(japaneseIngredients: string[]): string[] {
  return japaneseIngredients.map((ingredient) => {
    const normalized = ingredient.trim().toLowerCase();
    return JA_TO_EN[normalized] || ingredient;
  });
}

/**
 * Translate English ingredients to Japanese
 */
export function translateEnglishToJapanese(englishIngredients: string[]): string[] {
  return englishIngredients.map((ingredient) => {
    const normalized = ingredient.trim().toLowerCase();
    return EN_TO_JA[normalized] || ingredient;
  });
}

