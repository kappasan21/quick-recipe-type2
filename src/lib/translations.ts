export function translateRecipeToJapanese(recipe: {
  name: string;
  ingredients: string[];
  instructions: string;
}): {
  name: string;
  ingredients: string[];
  instructions: string;
} {
  return {
    ...recipe,
    name: translateRecipeNameToJapanese(recipe.name),
    instructions: translateRecipeInstructionsToJapanese(recipe.instructions),
    ingredients: translateEnglishToJapanese(recipe.ingredients),
  };
}

/**
 * Check if a string contains Japanese characters
 */
export function containsJapanese(text: string): boolean {
  const japaneseRegex = /[\u3040-\u309F\u30A0-\u30FF\u4E00-\u9FFF]/g;
  return japaneseRegex.test(text);
}
